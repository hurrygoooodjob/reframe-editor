import { build } from 'esbuild';
import { mkdir,writeFile,copyFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const result=await build({entryPoints:[path.join(root,'src/vision/worker.ts')],bundle:true,write:false,format:'iife',platform:'browser',target:'es2020',minify:true,legalComments:'eof'});
await writeFile(path.join(root,'src/vision/generated-worker.ts'),`// Generated by scripts/build-vision.mjs; do not edit.\nexport default ${JSON.stringify(result.outputFiles[0].text)};\n`);
await mkdir(path.join(root,'public/vision'),{recursive:true});
for(const name of ['vision_wasm_internal.js','vision_wasm_internal.wasm','vision_wasm_nosimd_internal.js','vision_wasm_nosimd_internal.wasm'])await copyFile(path.join(root,'node_modules/@mediapipe/tasks-vision/wasm',name),path.join(root,'public/vision',name));
console.log('Local vision worker and pinned WASM resources ready.');
