import { build } from 'esbuild';
import { mkdir, readFile, writeFile, cp } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
process.chdir(root);
await import('./build-vision.mjs');
const worker = await build({ entryPoints: ['src/engine/worker.ts'], bundle: true, write: false, format: 'iife', platform: 'browser', target: 'es2020', minify: true });
await writeFile('src/generated-worker.ts', `// Generated by scripts/build.mjs.\nexport default ${JSON.stringify(worker.outputFiles[0].text)};\n`);
if (process.argv.includes('--worker-only')) process.exit(0);
const result = await build({entryPoints:['src/main.tsx'],bundle:true,write:false,outdir:'dist',format:'iife',platform:'browser',target:'es2020',minify:true,loader:{'.jpg':'dataurl','.png':'dataurl'},define:{'process.env.NODE_ENV':'"production"'},legalComments:'eof'});
const js = result.outputFiles.find(f=>f.path.endsWith('.js')).text.replace(/<\/script/gi,'<\\/script');
const css = result.outputFiles.find(f=>f.path.endsWith('.css'))?.text || '';
const html = `<!doctype html><html lang="zh-CN"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover"><meta name="theme-color" content="#7187a3"><link rel="icon" href="data:,"/><title>Niuniu · 图片塑形工具</title><style>${css}</style></head><body><div id="root"></div><script>${js}</script></body></html>`;
await mkdir('dist',{recursive:true});
await writeFile('dist/index.html',html);
await cp('public','dist',{recursive:true});
console.log(`Built offline app: ${(Buffer.byteLength(html)/1024).toFixed(0)} KB`);
